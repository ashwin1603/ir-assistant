"""Per-incident generated artifacts: an IOC list and response scripts.

IOCs come only from the events that the incident's detections matched (the
evidence), never from the whole log. The scripts are returned as TEXT for an
analyst to review; nothing here runs them, and the app never executes them.
"""

import csv
import hashlib
import io
import ipaddress
import json
import re

from sqlalchemy.orm import Session

from app.models import Detection, Event

# Built-in accounts that show up in almost every log; listing them as IOCs is noise.
IGNORED_USERS = {"-", "system", "local service", "network service"}
IOC_FIELDS = ["type", "value", "event_count", "event_ids"]
REVIEW_BANNER = (
    "# ==========================================================================\n"
    "# REVIEW BEFORE USE. Generated by IR Assistant from incident evidence.\n"
    "# This text was NOT executed by the application. Check every line, then run\n"
    "# it yourself from an elevated PowerShell prompt only if you agree with it.\n"
    "# ==========================================================================\n"
)


def _valid_ip(value: str | None) -> str | None:
    """Return the normalised IP, or None if it is not a usable remote address.
    Parsing with ipaddress also guarantees the value is safe to put in a script."""
    try:
        ip = ipaddress.ip_address((value or "").strip())
    except ValueError:
        return None
    if ip.is_loopback or ip.is_unspecified:
        return None
    return str(ip)


def extract_iocs(db: Session, incident_id: str) -> list[dict]:
    event_ids: set[str] = set()
    for d in db.query(Detection).filter(Detection.incident_id == incident_id).all():
        event_ids.update(json.loads(d.matched_event_ids))
    events = db.query(Event).filter(Event.id.in_(event_ids)).all() if event_ids else []

    found: dict[tuple[str, str], set[str]] = {}

    def add(ioc_type: str, value: str | None, event_id: str) -> None:
        if value:
            found.setdefault((ioc_type, value), set()).add(event_id)

    for e in events:
        add("ip", _valid_ip(e.src_ip), e.id)
        if e.user and e.user.strip().lower() not in IGNORED_USERS:
            add("user", e.user.strip(), e.id)
        for path in (e.process, e.parent_process):
            if path and path.strip() != "-":
                add("process", path.strip(), e.id)
        if e.command_line:
            add("cmdline_sha256", hashlib.sha256(e.command_line.encode("utf-8")).hexdigest(), e.id)

    return [
        {"type": t, "value": v, "event_count": len(ids), "event_ids": sorted(ids)}
        for (t, v), ids in sorted(found.items())
    ]


def _csv_safe(value: str) -> str:
    # Stop spreadsheet formula injection: log data is attacker-controlled.
    return "'" + value if value[:1] in ("=", "+", "-", "@", "\t", "\r") else value


def iocs_to_csv(iocs: list[dict]) -> str:
    out = io.StringIO()
    writer = csv.writer(out)
    writer.writerow(IOC_FIELDS)
    for ioc in iocs:
        writer.writerow([ioc["type"], _csv_safe(ioc["value"]), ioc["event_count"], " ".join(ioc["event_ids"])])
    return out.getvalue()


def _safe_label(text: str) -> str:
    # Host names are log data; keep only harmless characters before putting them in a script comment.
    return re.sub(r"[^A-Za-z0-9._-]", "_", text)[:64]


def firewall_block_script(host: str, incident_id: str, iocs: list[dict]) -> str:
    ips = [ioc["value"] for ioc in iocs if ioc["type"] == "ip"]
    lines = [REVIEW_BANNER, f"# Windows Firewall blocks for incident {_safe_label(incident_id)} on host {_safe_label(host)}", ""]
    if not ips:
        lines.append("# No remote IP addresses were found in this incident's evidence. Nothing to block.")
        return "\n".join(lines) + "\n"
    for ip in ips:
        name = f"IR-Block-{ip.replace(':', '_')}"
        lines.append(f'New-NetFirewallRule -DisplayName "{name}-In" -Direction Inbound -RemoteAddress {ip} -Action Block')
        lines.append(f'New-NetFirewallRule -DisplayName "{name}-Out" -Direction Outbound -RemoteAddress {ip} -Action Block')
    lines += ["", "# Rollback:", '# Get-NetFirewallRule -DisplayName "IR-Block-*" | Remove-NetFirewallRule']
    return "\n".join(lines) + "\n"


def isolation_script(host: str, incident_id: str) -> str:
    return (
        REVIEW_BANNER
        + f"# Host isolation for incident {_safe_label(incident_id)} on host {_safe_label(host)}\n"
        + "# Blocks all inbound and outbound traffic except to one analyst/management IP.\n"
        + "# Existing Allow rules still apply; review them with: Get-NetFirewallRule -Action Allow\n"
        + "#Requires -RunAsAdministrator\n"
        + "\n"
        + '$AnalystIp = "REPLACE-WITH-YOUR-MANAGEMENT-IP"   # edit before running\n'
        + "\n"
        + "# Save the current firewall config so it can be restored.\n"
        + 'netsh advfirewall export "$env:TEMP\\ir-firewall-backup.wfw"\n'
        + "\n"
        + 'New-NetFirewallRule -DisplayName "IR-Isolation-Allow-Analyst-In" -Direction Inbound -RemoteAddress $AnalystIp -Action Allow\n'
        + 'New-NetFirewallRule -DisplayName "IR-Isolation-Allow-Analyst-Out" -Direction Outbound -RemoteAddress $AnalystIp -Action Allow\n'
        + "Set-NetFirewallProfile -Profile Domain,Private,Public -Enabled True -DefaultInboundAction Block -DefaultOutboundAction Block\n"
        + "\n"
        + "# Rollback:\n"
        + '# netsh advfirewall import "$env:TEMP\\ir-firewall-backup.wfw"\n'
        + '# Get-NetFirewallRule -DisplayName "IR-Isolation-*" | Remove-NetFirewallRule\n'
    )
